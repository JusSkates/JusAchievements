    id("org.jetbrains.kotlin.plugin.serialization")
}

android {
    namespace = "app.jusachievements"
    compileSdk = 37

    defaultConfig {
        applicationId = "app.jusachievements"
        minSdk = 26
        targetSdk = 37
        versionCode = 2
        versionName = "0.1.1"
    }

    // Release signing key lives outside the repo. Point JA_KEYSTORE_PROPERTIES at a properties
    // file (storeFile, storePassword, keyAlias, keyPassword), or put it in the default location.
    // Without one, release builds fall back to the debug key so anyone can still build the app.
    val keystoreProps = Properties().apply {
        val file = File(
            System.getenv("JA_KEYSTORE_PROPERTIES")
                ?: rootProject.file("../JusAchievements-signing/keystore.properties").path
        )
        if (file.isFile) file.inputStream().use { load(it) }
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = File(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Not minified yet: keeps the public build identical in behaviour to the tested one.
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

